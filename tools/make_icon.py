#!/usr/bin/env python3
"""Builds Lantern's icon from the art in src/Lantern/Media.

    python tools/make_icon.py

Why a generated file is committed rather than generated by the build: the icon has to be inside the
executable, which means the compiler wants `Media/icon.ico` to exist before anything else happens, and
the sizes have to be chosen by somebody looking at the picture rather than by whatever shrink Windows
happens to pick at the moment a title bar is painted.

What goes wrong if you only hand Windows the 1254-pixel original: it takes the closest frame it is
offered to the size it asked for, so every one of a title bar's 16 pixels, the taskbar's 24, and
Explorer's 48 is the same giant picture scaled by a stranger. Measured on this art at 16 pixels, the
lantern's flame is seven pixels of warm colour in a 256-pixel picture - there is nothing left to
recognise, and there would be even less if it had been shrunk with a cheaper filter than Lanczos.

So this writes one picture per size Windows asks for, smallest first. The order is not cosmetic:
`new Icon(path)` in .NET reads the first entry in the file, and that is the picture a window gets
before Windows swaps in a better one for the size it is drawing - so the first entry is a title bar
picture, and `AppIcon.Current.ToBitmap()` gives back 16 pixels rather than 256.

The art is `icon_trans.png` and not `icon.png`: the opaque version of the same drawing has the
background baked into it, and a filled square in the corner of a title bar looks like a window with a
hole punched in the theme. The transparent art is about half empty (47% of its pixels at 16x16), which
is what `AppIconTests` checks for.

Requires Pillow (`pip install pillow`). The output is deterministic apart from the PNG encoder's own
bytes, so re-running this on the same art only changes the file if the art changed.
"""

from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "src" / "Lantern" / "Media" / "icon_trans.png"
TARGET = ROOT / "src" / "Lantern" / "Media" / "icon.ico"

# Every size Windows is known to ask for: 16 for a title bar and a menu, 24 for a taskbar button at
# 100% scale, 32 for a title bar at larger scales and the alt-tab strip, 48 and up for Explorer's
# icon views, and 256 for "extra large", which is stored as a PNG inside the container since Vista.
SIZES = [(16, 16), (24, 24), (32, 32), (48, 48), (64, 64), (128, 128), (256, 256)]


def main() -> None:
    if not SOURCE.exists():
        raise SystemExit(f"no art at {SOURCE}")

    art = Image.open(SOURCE).convert("RGBA")

    if art.width != art.height:
        raise SystemExit(
            f"{SOURCE.name} is {art.width}x{art.height}; an icon frame is square, so it would be"
            " squashed or letterboxed and nobody should be deciding which by accident"
        )

    art.save(TARGET, format="ICO", sizes=SIZES, bitmap_format="rgba")

    written = Image.open(TARGET)
    frames = sorted(written.ico.sizes())

    listing = ", ".join(f"{w}x{h}" for w, h in frames)
    print(f"{TARGET.relative_to(ROOT)}: {TARGET.stat().st_size:,} bytes, {len(frames)} frames: {listing}")

    missing = [s for s in SIZES if tuple(s) not in frames]

    if missing:
        raise SystemExit(f"Pillow did not write {missing} - Windows will scale what it finds instead")


if __name__ == "__main__":
    main()
